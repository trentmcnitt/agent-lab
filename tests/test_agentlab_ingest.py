def _needs(lib, name):
    if name not in lib:
        pytest.skip("agentlab.langgraph or LangGraph isn't installed in the library's environment")
    return lib[name]


def test_the_langgraph_quickstart_reads_as_its_graph(lib):
    state, evs = ingest(_needs(lib, "lg_quickstart")["batches"])
    assert all(not list(EVENT.iter_errors(e)) for e in evs)
    assert len({e["run_id"] for e in evs}) == 1
    rs = evs[0]["data"]
    assert evs[0]["event_type"] == "run_started" and rs["app"] == "support-assistant" and rs["map_hash"]
    manifest = state.maps[rs["map_hash"]]
    on_map = {n["id"] for n in manifest["nodes"]}
    ran = [e["node"] for e in evs if e["event_type"] == "step_started"]
    assert ran and set(ran) <= on_map, "every step is a node of the graph's own map"
    steps = {e["step_id"]: e["node"] for e in evs if e["event_type"] == "step_started"}
    for e in evs:
        if e["event_type"] in ("llm_call", "retrieval", "decision", "check_result"):
            assert steps.get(e["step_id"]) == e["node"], f"{e['event_type']} on {e['node']} isn't on its node's step"
    assert any(e["event_type"] == "llm_call" for e in evs) and evs[-1]["event_type"] == "run_finished"


def test_a_real_interrupt_is_one_gate_step(lib):
    pause, resume = _needs(lib, "lg_gate")["batches"]
    state = otlp.TraceState()
    a = state.ingest(copy.deepcopy(pause))
    assert not any(e["event_type"] == "run_finished" for e in a)
    rid = a[0]["run_id"]
    assert state.run_info(rid)["status"] == "paused"
    b = state.ingest(copy.deepcopy(resume))
    assert {e["run_id"] for e in b} == {rid} and not any(e["event_type"] == "run_started" for e in b)
    gate = [e for e in a + b if e["node"] == "gate"]
    assert [e["event_type"] for e in gate] == ["step_started", "gate_waiting", "gate_resolved", "step_finished"]
    assert len({e["step_id"] for e in gate}) == 1
    assert gate[1]["data"]["proposed"] == {"action_type": "create_ticket", "title": "Access to Compass"}
    assert b[-1]["event_type"] == "run_finished" and b[-1]["data"]["outcome"] == "executed"
    # The branch taken is derived from what ran next; the map has it.
    edges = state.maps[a[0]["data"]["map_hash"]]["edges"]
    assert {"from": "gate", "to": "act", "from_branch": "approved"} in [
        {k: e[k] for k in ("from", "to", "from_branch") if k in e} for e in edges]


