def test_a_run_reads_as_bench_events(lib):
    state, evs = ingest(lib["answer"]["batches"])
    assert all(not list(EVENT.iter_errors(e)) for e in evs)
    assert {e["run_id"] for e in evs} == {"t1:aaaa0001"}
    assert [e["seq"] for e in evs] == list(range(len(evs)))
    assert kinds(evs) == [
        ("_run", "run_started"),
        ("retrieve", "step_started"), ("retrieve", "retrieval"), ("retrieve", "step_finished"),
        ("classify", "step_started"), ("classify", "llm_call"), ("classify", "decision"),
        ("classify", "check_result"), ("classify", "step_finished"),
        ("grounding_check", "step_started"), ("grounding_check", "check_result"), ("grounding_check", "step_finished"),
        ("respond", "step_started"), ("respond", "step_finished"),
        ("_run", "run_finished")]
    by = {e["event_type"]: e for e in evs}
    rs = by["run_started"]["data"]
    assert rs["map_hash"] == lib["answer"]["map_hash"] and rs["app"] == APP and rs["thread"] == "t1"
    assert rs["input"] == {"text": "How do I reset my password?"}
    assert {e.get("session_id") for e in evs} == {"sess-1"}
    assert by["decision"]["data"] == {"rationale": "The handbook covers password resets.", "confidence": 0.9, "cited": ["sec-1"]}
    ck = next(e for e in evs if e["event_type"] == "check_result" and e["data"]["name"] == "unsure")["data"]
    assert ck["state"] == "passed" and ck["words"] == {"passed": "Sure enough", "failed": "Sent to a person"}
    llm = by["llm_call"]
    assert llm["data"]["params"]["json_schema"]["properties"]["category"]["enum"] == ["answerable", "needs_write"]
    assert llm["data"]["input_tokens"] == 120 and llm["data"]["cache_read_tokens"] == 100
    # A model call and a search are content of their node's step, not steps of their own.
    steps = {e["node"]: e["step_id"] for e in evs if e["event_type"] == "step_started"}
    assert llm["step_id"] == steps["classify"] and by["retrieval"]["step_id"] == steps["retrieve"]
    assert by["retrieval"]["data"]["source"] == "handbook" and "stale_index" not in by["retrieval"]["data"]
    # a retriever's other numeric scores reach the event (a story may show them)
    hit = by["retrieval"]["data"]["hits"][0]
    assert hit["score"] == 0.9 and hit["bm25"] == 7.25 and "bm25" not in by["retrieval"]["data"]["hits"][1]
    rf = by["run_finished"]["data"]
    assert rf == {**rf, "status": "ok", "outcome": "answered", "output": {"reply": "Use the self-service portal."},
                  "baseline": "~10 minutes"}
    assert state.maps[rs["map_hash"]] == lib["answer"]["manifest"]
    assert state.take_maps() == [(rs["map_hash"], lib["answer"]["manifest"])] and state.take_maps() == []


def test_the_map_arrives_first_and_the_run_span_last(lib):
    """One POST per span, in the order spans end (the exporter's order): the run opens on the
    manifest span with its map; the input arrives with the run span as run_updated."""
    batches = lib["answer_split"]["batches"]
    state = otlp.TraceState()
    first = state.ingest(copy.deepcopy(batches[0]))
    assert kinds(first) == [("_run", "run_started")]
    assert first[0]["data"]["map_hash"] == lib["answer"]["map_hash"]
    rest = [e for b in batches[1:] for e in state.ingest(copy.deepcopy(b))]
    whole = ingest(lib["answer"]["batches"])[1]
    assert sorted(kinds(first + rest)) == sorted(kinds(whole) + [("_run", "run_updated")])
    upd = next(e for e in rest if e["event_type"] == "run_updated")
    assert upd["data"] == {"input": {"text": "How do I reset my password?"}}
    assert [e["seq"] for e in first + rest] == list(range(len(first + rest)))


