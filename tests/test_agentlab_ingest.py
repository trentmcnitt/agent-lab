"""The bench reads what the `agentlab` library writes (SPEC.md 8.6): runs by `agentlab.run`, the map
each run carries, the facts as bench events, stories from trusted files, and `bench.record`.

The spans are generated by the library itself on every test run (tests/fixtures/agentlab/scenarios.py,
in the library's own environment), never checked in, so the bench is always tested against what the
library writes today.
"""
