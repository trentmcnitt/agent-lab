# ---- through the viewer's own logic -------------------------------------------------------------------

def _viewer(recording_rows, tmp_path):
    """Runs viewer/logic.js (the code the viewer runs) over a recording: its map checks and sources."""
    p = tmp_path / "rec.jsonl"
    p.write_text("".join(json.dumps(r) + "\n" for r in recording_rows))
    script = """
      import * as L from '%s';
      import fs from 'node:fs';
      const rows = fs.readFileSync(process.argv[1], 'utf8').split('\\n').filter(Boolean).map(JSON.parse);
      const topo = rows[0].topology, events = L.sortEvents(rows.slice(1).map(L.normalizeEvent));
      const run = L.newRun('r'); events.forEach((e) => L.reduce(run, e, 0));
      console.log(JSON.stringify({checks: L.mapChecks(topo, events), sources: L.sourceStates(topo, events)
        .map((s) => ({id: s.id, line: L.sourceCountsLine(s), givenKnown: s.givenKnown})),
        rows: L.checkStates(topo, events, true).map((r) => r.line), baseline: L.baselineOf(events, topo),
        outcome: L.outcome(topo, events).text, hash: L.runMapHash(events), input: run.input}));
    """ % (ROOT / "viewer/logic.js").as_uri()
    r = subprocess.run(["node", "--input-type=module", "-e", script, str(p)], capture_output=True, text=True, timeout=60)
    assert r.returncode == 0, r.stderr
    return json.loads(r.stdout)


def test_viewer_logic_reads_a_library_run(lib, tmp_path):
    rows = record.record(merged(lib["answer"]["batches"]), name="x", stories={APP: lib["_story"]})[0][1]
    v = _viewer(rows, tmp_path)
    assert [f["code"] for f in v["checks"] if f["from"] == "run"] == []
    assert {f["code"] for f in v["checks"]} <= {"R12"}, "the scenario's map has words missing (info), nothing else"
    assert v["sources"] == [{"id": "handbook", "line": "3 available · 1 given to the AI · 1 relied on", "givenKnown": True}]
    assert "✓ Sure enough." in v["rows"]
    assert v["baseline"] == "~10 minutes" and v["outcome"] == "Answered"
    assert v["hash"] == lib["answer"]["map_hash"] and v["input"] == {"text": "How do I reset my password?"}


def test_viewer_logic_flags_what_a_bad_run_reports(lib, tmp_path):
    rows = record.record(merged(lib["bad_facts"]["batches"]), name="x")[0][1]
