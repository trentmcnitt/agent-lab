def test_a_gate_is_one_step_across_the_pause_and_the_resume(lib):
    pause, resume = lib["gate"]["batches"]
    state = otlp.TraceState()
    a = state.ingest(copy.deepcopy(pause))
    assert ("_run", "run_finished") not in kinds(a), "a paused run isn't finished"
    assert kinds(a)[-1] == ("approval_gate", "gate_waiting"), "the gate's step stays open"
    assert state.run_info("t2:bbbb0002")["status"] == "paused"
    b = state.ingest(copy.deepcopy(resume))
    evs = a + b
    assert sum(e["event_type"] == "run_started" for e in evs) == 1
    gate = [e for e in evs if e["node"] == "approval_gate"]
    assert [e["event_type"] for e in gate] == ["step_started", "gate_waiting", "gate_resolved", "step_finished"]
    assert len({e["step_id"] for e in gate}) == 1
    assert next(e for e in gate if e["event_type"] == "gate_resolved")["data"] == {"approved": True, "by": "Dana (IT lead)"}
    assert ("execute_action", "ticket_opened") in kinds(b)
    assert kinds(b)[-1] == ("_run", "run_finished") and b[-1]["data"]["outcome"] == "executed"
    assert [e["seq"] for e in evs] == list(range(len(evs)))


