def test_the_bench_keeps_and_serves_each_runs_map(c, lib, tmp_path):
    h = lib["answer"]["map_hash"]
    assert c.post("/v1/traces", json=lib["answer"]["batches"][0]).status_code == 200
    assert c.get(f"/maps/{h}").json() == lib["answer"]["manifest"]
    assert json.loads((tmp_path / "maps" / f"{h}.json").read_text()) == lib["answer"]["manifest"]
    assert c.get("/maps/" + "0" * 64).status_code == 404
    assert c.get("/maps/not-a-hash").status_code == 404
    # The existing viewer asks for an app's map: it gets the one its latest run carried.
    assert c.get(f"/topology/{APP}").json() == lib["answer"]["manifest"]
    assert c.get("/topologies").json() == [{"id": APP, "name": "Helpdesk (scenario)", "story": False, "map_hash": h}]
    run = c.get("/runs").json()[0]
    assert run["map_hash"] == h and run["app"] == APP and run["status"] == "ok"
    # A restarted bench reads the map from disk, and checks it again.
    srv.store.maps.clear()
    assert c.get(f"/maps/{h}").json() == lib["answer"]["manifest"]
    srv.store.maps.clear()
    (tmp_path / "maps" / f"{h}.json").write_text(json.dumps({**lib["answer"]["manifest"], "never": ["edited"]}))
    assert c.get(f"/maps/{h}").status_code == 404


