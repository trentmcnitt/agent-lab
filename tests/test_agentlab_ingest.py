def _manifest_attr(body):
    span = next(s for s in spans_of(body) if attr(s, "agentlab.kind")["value"]["stringValue"] == "manifest")
    return attr(span, "agentlab.manifest")["value"]


@pytest.mark.parametrize("damage", ["truncated", "altered", "not_a_map"])
def test_a_damaged_map_is_refused_never_half_used(lib, damage):
    body = copy.deepcopy(lib["answer"]["batches"][0])
    v = _manifest_attr(body)
    if damage == "truncated":    # what OTEL_ATTRIBUTE_VALUE_LENGTH_LIMIT does
        v["stringValue"] = v["stringValue"][: len(v["stringValue"]) // 2]
    elif damage == "altered":
        v["stringValue"] = v["stringValue"].replace("Helpdesk (scenario)", "Helpdesk (edited)")
    else:
        v["stringValue"] = "[1, 2]"
    state, evs = ingest([body])
    rs = evs[0]["data"]
    assert "map_hash" not in rs and rs["map_error"].startswith("R13: ")
    assert state.take_maps() == [] and not state.maps
    # The run itself still shows: steps and facts don't depend on the map.
    assert ("classify", "decision") in kinds(evs) and kinds(evs)[-1] == ("_run", "run_finished")


def test_a_map_valid_by_hash_but_not_a_bench_map_is_refused():
    manifest = {"v": "bench-topology/0", "app": {"id": "BAD ID", "name": "x"}, "nodes": [], "edges": []}
    raw = otlp.canonical(manifest).decode()
    m, h, err = otlp.verify_manifest(raw, otlp.sha256_hex(manifest))
