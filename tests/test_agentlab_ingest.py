@pytest.fixture(scope="session")
def lib(tmp_path_factory):
    """{scenario: {...}} plus the story file, written by the library (see the module docstring)."""
    out = tmp_path_factory.mktemp("agentlab")
    r = subprocess.run(["uv", "run", "--quiet", "--project", str(ROOT / "sdk/python"), "python",
                        str(ROOT / "tests/fixtures/agentlab/scenarios.py"), str(out)],
                       capture_output=True, text=True, timeout=300, cwd=ROOT)
    assert r.returncode == 0, r.stderr[-3000:]
    data = json.loads((out / "scenarios.json").read_text())
    data["_story"] = out / f"{APP}.story.js"
    return data


def ingest(batches, state=None):
    state = state or otlp.TraceState()
    return state, [e for b in batches for e in state.ingest(copy.deepcopy(b))]


def merged(batches):
    return {"resourceSpans": [rs for b in batches for rs in copy.deepcopy(b)["resourceSpans"]]}


def kinds(events):
    return [(e["node"], e["event_type"]) for e in events]


def spans_of(body):
    return [s for rs in body["resourceSpans"] for ss in rs["scopeSpans"] for s in ss["spans"]]


def attr(span, key):
    return next((a for a in span["attributes"] if a["key"] == key), None)


